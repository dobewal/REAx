"""Markdown report: human-readable, paste-able, diff-friendly."""

from __future__ import annotations

from typing import Any


def _grade_badge(grade: str) -> str:
    return {"low": "🟢", "medium": "🟡", "high": "🟠", "critical": "🔴"}.get(grade, "⚪")


def _sev_emoji(sev: int) -> str:
    return {0: "·", 1: "🟡", 2: "🟠", 3: "🔴"}.get(sev, "·")


def _breakdown_md(risk: dict[str, Any]) -> list[str]:
    bd = risk.get("breakdown")
    if not bd:
        return []
    L = ["## Score breakdown", ""]
    for k, v in bd.items():
        bar = "█" * (v // 5) + "░" * (5 - v // 5)
        L.append(f"- {k.capitalize():<12} {bar} {v}/25")
    L.append("")
    return L


def render(ev: dict[str, Any]) -> str:
    if ev["target"]["kind"] == "elf":
        return render_elf(ev)
    return render_apk(ev)


def render_elf(ev: dict[str, Any]) -> str:
    t = ev["target"]
    s = ev["sections"]
    risk = s.get("risk", {})
    ident = s.get("identity", {})
    imports = s.get("imports", {})
    exports = s.get("exports", {})
    secs = s.get("sections_info", {})
    segs = s.get("segments", {})
    net = s.get("network_indicators", {})

    L: list[str] = []
    A = L.append
    A(f"# REAX report — `{t['name']}`")
    A("")
    A(f"**Verdict: {_grade_badge(risk.get('grade', ''))} {risk.get('grade', 'unknown').upper()}** — risk score **{risk.get('score', 0)}/100**")
    A("")
    for f in risk.get("findings", []):
        A(f"- { {'high': '🔴', 'medium': '🟡', 'low': '🟢'}.get(f.get('level'), '·') } {f.get('text')}")
    A("")
    L.extend(_breakdown_md(risk))
    A("## Binary identity")
    A("")
    A(f"- Architecture: {ident.get('arch')} ({ident.get('bits')}-bit, {ident.get('endian')}-endian)")
    A(f"- Type: {ident.get('type')} · Stripped: {ident.get('stripped')}")
    A(f"- SHA256: `{t.get('sha256', '')[:32]}…`")
    A("")
    A("## Suspicious imports")
    A("")
    susp = [r for r in imports.get("items", []) if r["severity"] > 0]
    if susp:
        A("| Function | Risk | Why |")
        A("|---|---|---|")
        for r in susp:
            A(f"| `{r['function']}` | {_sev_emoji(r['severity'])} | {r['why']} |")
    else:
        A("None.")
    A("")
    A(f"Total imported functions: {imports.get('count', 0)} · "
      f"Exported: {exports.get('count', 0)}")
    if imports.get("libraries"):
        A(f"Linked libraries: {', '.join(imports['libraries'][:8])}")
    A("")
    A("## Sections")
    A("")
    A(f"{secs.get('count', 0)} sections.")
    A("")
    A("| Section | Size | Entropy | W | X |")
    A("|---|---|---|---|---|")
    for sec in (secs.get("largest") or [])[:12]:
        flag = " 🔥" if sec["entropy"] > 7.5 else ""
        A(f"| `{sec['name']}` | {sec['size']:,} | {sec['entropy']}{flag} | "
          f"{'✓' if sec['write'] else ''} | {'✓' if sec['exec'] else ''} |")
    A("")
    if segs.get("rwx_count"):
        A(f"⚠️ **{segs['rwx_count']} RWX segment(s)** — memory that is readable, writable AND executable.")
        A("")
    if s.get("packers"):
        A(f"📦 Packer signature: {', '.join(s['packers'])}")
        A("")
    A("## Network indicators")
    A("")
    A(f"- URLs in binary: {net.get('url_count')} · IPs: {net.get('ip_count')}")
    for u in (net.get("urls") or [])[:15]:
        A(f"  - `{u}`")
    A("")
    A(f"_Generated by REAX {ev.get('reax_version')} — for educational and authorized security research only. See DISCLAIMER.md._")
    return "\n".join(L)


def render_apk(ev: dict[str, Any]) -> str:
    t = ev["target"]
    s = ev["sections"]
    risk = s.get("risk", {})
    ident = s.get("identity", {})
    perms = s.get("permissions", {})
    comp = s.get("components", {})
    libs = s.get("native_libraries", {})
    sign = s.get("signing", {})
    dex = s.get("dex", {})
    trackers = s.get("trackers", {})
    apis = s.get("suspicious_apis", {})
    net = s.get("network_indicators", {})

    L: list[str] = []
    A = L.append

    A(f"# REAX report — `{t['name']}`")
    A("")
    A(f"**Verdict: {_grade_badge(risk.get('grade', ''))} {risk.get('grade', 'unknown').upper()}** — risk score **{risk.get('score', 0)}/100**")
    A("")
    for f in risk.get("findings", []):
        A(f"- { {'high': '🔴', 'medium': '🟡', 'low': '🟢'}.get(f.get('level'), '·') } {f.get('text')}")
    A("")
    L.extend(_breakdown_md(risk))
    A("## Identity")
    A("")
    A(f"- Package: `{ident.get('package')}`")
    A(f"- App: {ident.get('app_name')}")
    A(f"- Version: {ident.get('version_name')} (code {ident.get('version_code')})")
    A(f"- SDK: min {ident.get('min_sdk')} / target {ident.get('target_sdk')}")
    A(f"- Main activity: `{ident.get('main_activity')}`")
    A(f"- Debuggable: {ident.get('debuggable')} · allowBackup: {ident.get('allow_backup')}")
    A(f"- SHA256: `{t.get('sha256', '')[:32]}…`")
    A("")
    A("## Permissions")
    A("")
    A(f"{perms.get('count', 0)} permissions declared.")
    A("")
    A("| Permission | Risk | Why |")
    A("|---|---|---|")
    for p in perms.get("items", []):
        if p["severity"] > 0:
            A(f"| `{p['permission']}` | {_sev_emoji(p['severity'])} | {p['why']} |")
    A("")
    A("## Trackers")
    A("")
    if trackers.get("items"):
        for tr in trackers["items"]:
            A(f"- 🛰️ {tr}")
    else:
        A("None detected.")
    A("")
    A("## Components")
    A("")
    A(f"- Activities: {comp.get('activities')} · Services: {comp.get('services')} · "
      f"Receivers: {comp.get('receivers')} · Providers: {comp.get('providers')}")
    if comp.get("features"):
        A(f"- Features: {', '.join(comp['features'][:10])}")
    A("")
    A("## Native libraries")
    A("")
    if libs.get("items"):
        for lib in libs["items"][:30]:
            A(f"- `{lib}`")
    else:
        A("None.")
    A("")
    A("## Code")
    A("")
    A(f"- DEX files: {dex.get('dex_files')} · Classes: {dex.get('classes')} · Methods: {dex.get('methods')}")
    A("")
    if apis.get("items"):
        A("### Suspicious API usage")
        A("")
        for a in apis["items"][:20]:
            A(f"- `{a['api']}` — {a['hits']} call sites")
        A("")
    A("## Network indicators")
    A("")
    A(f"- URLs in strings: {net.get('url_count')} · IPs: {net.get('ip_count')}")
    for u in (net.get("urls") or [])[:15]:
        A(f"  - `{u}`")
    A("")
    A("## Signing")
    A("")
    A(f"- Signed: {sign.get('signed')} (v1={sign.get('v1')} v2={sign.get('v2')} v3={sign.get('v3')})")
    A("")
    A(f"_Generated by REAX {ev.get('reax_version')} — for educational and authorized security research only. See DISCLAIMER.md._")
    return "\n".join(L)
